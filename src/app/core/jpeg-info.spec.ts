import { describe, expect, it } from 'vitest';
import { jpegNeedsRaster, readJpegDpi, readJpegOrientation } from './jpeg-info';

describe('jpeg info', () => {
  it('reads JFIF density as dots per inch', () => {
    const jpeg = new Uint8Array([
      0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x01, 0x00,
      0x96, 0x00, 0xc8, 0x00, 0x00,
    ]);
    expect(readJpegDpi(jpeg)).toEqual({ x: 150, y: 200 });
    expect(jpegNeedsRaster(jpeg)).toBe(false);
  });

  it('reads little-endian EXIF orientation', () => {
    const exif = new Uint8Array([
      0xff, 0xd8, 0xff, 0xe1, 0x00, 0x1e, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00, 0x49, 0x49, 0x2a,
      0x00, 0x08, 0x00, 0x00, 0x00, 0x01, 0x00, 0x12, 0x01, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00,
      0x06, 0x00, 0x00, 0x00,
    ]);
    expect(readJpegOrientation(exif)).toBe(6);
    expect(jpegNeedsRaster(exif)).toBe(true);
  });
});
